import { test, expect, type Page } from '@playwright/test'

async function identity(page: Page, role: string, user: string) {
  await page.goto('/login')
  await page.getByLabel('演示角色', { exact: true }).click()
  await page.locator('.n-base-select-menu:visible').getByText(role, { exact: true }).click()
  await page.getByLabel('演示用户', { exact: true }).click()
  await page.locator('.n-base-select-menu:visible').getByText(user, { exact: true }).click()
  await page.getByRole('button', { name: '进入演示工作区', exact: true }).click()
  await expect(page.getByRole('heading', { name: '工作台', exact: true })).toBeVisible()
}
test('catalog favorites remain private between users with the same role', async ({ page }) => {
  await identity(page, '只读分析师', '演示用户 3')
  await page.goto('/governance/catalog?q=零售订单库')
  const row = page.getByRole('row').filter({ hasText: '零售订单库' })
  await row.getByRole('button', { name: '收藏', exact: true }).click()
  await expect(row.getByRole('button', { name: '取消收藏', exact: true })).toBeVisible()
  await identity(page, '只读分析师', '演示用户 6')
  await page.goto('/governance/catalog?favorite=true')
  await expect(page.getByRole('button', { name: '零售订单库', exact: true })).toHaveCount(0)
  await page.goto('/governance/catalog?q=零售订单库')
  await expect(row.getByRole('button', { name: '收藏', exact: true })).toBeVisible()
  await identity(page, '只读分析师', '演示用户 3')
  await page.goto('/governance/catalog?favorite=true')
  await expect(row.getByRole('button', { name: '取消收藏', exact: true })).toBeVisible()
  await page.reload()
  await expect(row.getByRole('button', { name: '取消收藏', exact: true })).toBeVisible()
})

test('viewer columns stay hidden in table, query, service and downloaded CSV; results remain private', async ({
  page,
}) => {
  test.setTimeout(60000)
  await identity(page, '只读分析师', '演示用户 3')
  await page.goto('/sources/1001?objectId=11001&tab=preview')
  await expect(page.getByRole('columnheader', { name: 'id', exact: true })).toBeVisible()
  await expect(page.getByRole('columnheader', { name: 'phone', exact: true })).toHaveCount(0)
  await page.goto('/datasets/2001?tab=preview')
  await expect(page.getByRole('columnheader', { name: 'id', exact: true })).toBeVisible()
  await expect(page.getByRole('columnheader', { name: 'phone', exact: true })).toHaveCount(0)
  await page.goto('/warehouse/tables/4001?tab=sample')
  await expect(
    page.getByText('当前角色隐藏敏感列，查询、服务和导出遵循相同范围。', { exact: true }),
  ).toBeVisible()
  await expect(page.getByRole('columnheader', { name: 'id', exact: true })).toBeVisible()
  await expect(page.getByRole('columnheader', { name: 'phone', exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: '查询此表', exact: true }).click()
  await page.getByRole('button', { name: '运行查询', exact: true }).click()
  await expect(page.getByRole('button', { name: '导出 CSV', exact: true })).toBeEnabled()
  const queryUrl = page.url()
  await expect(page.getByRole('columnheader', { name: 'phone', exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: '导出 CSV', exact: true }).click()
  const download = page.waitForEvent('download')
  await page.getByRole('button', { name: '下载', exact: true }).click()
  const stream = await (await download).createReadStream()
  let csv = ''
  for await (const part of stream!) csv += part.toString()
  expect(csv).toContain('"id","customer","amount","city"')
  expect(csv).not.toContain('phone')
  await page.goto('/services/7001')
  await page.getByText('参数调用器', { exact: true }).click()
  await page.getByRole('button', { name: '模拟调用', exact: true }).click()
  await expect(page.getByRole('cell', { name: '100', exact: true })).toBeVisible()
  await expect(page.getByRole('columnheader', { name: 'phone', exact: true })).toHaveCount(0)
  await identity(page, '只读分析师', '演示用户 6')
  await page.goto('/warehouse/exports')
  await expect(page.getByRole('button', { name: '下载', exact: true })).toHaveCount(0)
  await page.goto(queryUrl)
  await expect(page.getByText('当前角色没有操作权限', { exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: '导出 CSV', exact: true })).toBeDisabled()
  await identity(page, '数据开发者', '演示用户 2')
  await page.goto('/sources/1001?objectId=11001&tab=preview')
  await expect(page.getByRole('columnheader', { name: 'phone', exact: true })).toBeVisible()
  await page.goto('/datasets/2001?tab=preview')
  await expect(page.getByRole('cell', { name: '138****0000', exact: true })).toBeVisible()
  await page.goto('/warehouse/tables/4001?tab=sample')
  await expect(page.getByRole('columnheader', { name: 'phone', exact: true })).toBeVisible()
  await expect(page.getByRole('cell', { name: '138****0000', exact: true })).toBeVisible()
})
