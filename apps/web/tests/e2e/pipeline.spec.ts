import { test, expect } from '@playwright/test'

test.beforeEach(async ({ page }) => {
  await page.addInitScript(() => {
    localStorage.setItem('jiuzhang.preference.session', 'demo')
    localStorage.setItem('jiuzhang.preference.role', 'developer')
  })
})

test('create dataset, preview, publish, run, inspect warehouse and export', async ({ page }) => {
  test.setTimeout(60000)
  const errors: string[] = []
  page.on('pageerror', (error) => errors.push(error.message))
  await page.goto('/datasets/new?sourceId=1001&objectId=11001')
  await page.getByPlaceholder('数据集名称', { exact: true }).fill('完整流程验收数据集')
  await page.getByLabel('所属目录', { exact: true }).click()
  await page.locator('.n-base-select-menu:visible').getByText('交易分析', { exact: true }).click()
  await page.getByText('输出与入仓', { exact: true }).click()
  await page.getByRole('textbox', { name: '主题域', exact: true }).fill('售后分析')
  await page.getByPlaceholder('dwd_demo_orders').fill('dwd_acceptance')
  const key = page.getByLabel('业务主键', { exact: true })
  await key.click()
  await page.locator('.n-base-select-option').getByText('id', { exact: true }).click()
  await page.getByRole('heading', { name: '新建数据集' }).click()
  await page.getByRole('button', { name: '预览样本', exact: true }).click()
  await expect(page.getByRole('cell', { name: '138****0000', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '保存草稿', exact: true }).click()
  await expect(page.getByRole('heading', { name: '完整流程验收数据集' })).toBeVisible()
  await expect(page.getByText('交易分析', { exact: true })).toBeVisible()
  const datasetUrl = page.url()
  await page.reload()
  await expect(page.getByRole('heading', { name: '完整流程验收数据集' })).toBeVisible()
  await page.getByRole('button', { name: '发布版本', exact: true }).click()
  await page.getByRole('button', { name: '确认发布', exact: true }).click()
  await expect(page.getByRole('button', { name: '运行', exact: true })).toBeEnabled()
  await page.getByRole('button', { name: '运行', exact: true }).click()
  await expect(page).toHaveURL(new RegExp('/runs/[0-9]+$'))
  await page.reload()
  await expect(page.getByText('成功', { exact: true })).toBeVisible({ timeout: 20000 })
  await page
    .getByRole('button', { name: /^100[0-9]+$/ })
    .last()
    .click()
  await expect(page).toHaveURL(new RegExp('/warehouse/tables/[0-9]+$'))
  await expect(page.getByRole('heading', { name: 'dwd_acceptance' })).toBeVisible()
  await page.getByText('来源与版本', { exact: true }).click()
  await expect(page.getByText('售后分析', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: '查询此表', exact: true }).click()
  await page.getByRole('button', { name: '运行查询', exact: true }).click()
  await expect(page.getByRole('cell', { name: '138****0000', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '导出 CSV', exact: true }).click()
  await expect(page).toHaveURL(new RegExp('/warehouse/exports$'))
  const downloadEvent = page.waitForEvent('download')
  await page.getByRole('button', { name: '下载', exact: true }).first().click()
  expect((await downloadEvent).suggestedFilename()).toMatch(/[.]csv$/)
  await page.goto(datasetUrl + '?tab=preview')
  await expect(page.getByRole('cell', { name: '138****0000', exact: true })).toBeVisible()
  expect(errors).toEqual([])
})

test('blocked retry creates a new run; cancellation stays terminal after refresh', async ({
  page,
}) => {
  test.setTimeout(45000)
  await page.goto('/runs/9001')
  await page.getByRole('button', { name: /^重试运行 [0-9]+$/ }).click()
  await expect(page).not.toHaveURL(new RegExp('/runs/9001$'))
  await expect(page.getByText('成功', { exact: true })).toBeVisible({ timeout: 20000 })
  await page.goto('/runs/9001')
  await expect(page.getByText('质量阻断', { exact: true }).first()).toBeVisible()
  await expect(page.getByRole('button', { name: /^重试运行 [0-9]+$/ })).toHaveCount(0)
  await page.goto('/runs/9010')
  await page.getByRole('button', { name: /^重试运行 [0-9]+$/ }).click()
  await page.getByRole('button', { name: /^取消运行 [0-9]+$/ }).click()
  await expect(page.getByText('已取消', { exact: true })).toBeVisible()
  await page.reload()
  await expect(page.getByText('已取消', { exact: true })).toBeVisible()
  await expect(page.getByText('尚未发布', { exact: true })).toBeVisible()
})
