import { test, expect, type Page } from '@playwright/test'

test.beforeEach(async ({ page }) => {
  await page.addInitScript(() => {
    localStorage.setItem('jiuzhang.preference.session', 'demo')
    if (!localStorage.getItem('jiuzhang.preference.role'))
      localStorage.setItem('jiuzhang.preference.role', 'developer')
  })
})
async function select(page: Page, label: string, option: string) {
  await page.getByLabel(label, { exact: true }).click()
  await page.locator('.n-base-select-menu:visible').getByText(option, { exact: true }).click()
}
test('folders persist hierarchy, guard drafts, retain published state and reject nonempty deletion', async ({
  page,
}) => {
  const errors: string[] = []
  page.on('pageerror', (error) => errors.push(error.message))
  await page.goto('/datasets')
  const sidebar = page.locator('aside').filter({ hasText: '数据集目录' })
  await sidebar.getByRole('button', { name: '新建目录', exact: true }).click()
  await page.getByRole('button', { name: '保存', exact: true }).click()
  await expect(page.getByText('请填写 1–80 个字符的目录名称', { exact: true })).toBeVisible()
  await page.getByRole('textbox', { name: '目录名称', exact: true }).fill('验收父目录')
  await page.getByRole('button', { name: '保存', exact: true }).click()
  await expect(page).toHaveURL(/folderId=[0-9]+/)
  const parentUrl = page.url()
  await sidebar.getByRole('button', { name: '新建目录', exact: true }).click()
  await page.getByRole('textbox', { name: '目录名称', exact: true }).fill('验收子目录')
  await page.getByRole('button', { name: '保存', exact: true }).click()
  await expect(page).not.toHaveURL(parentUrl)
  const childUrl = page.url()
  await sidebar.getByRole('button', { name: '全部数据集', exact: true }).click()
  const row = page.getByRole('row').filter({ hasText: '订单明细宽表' })
  await row.getByRole('button', { name: '移动到目录', exact: true }).click()
  await select(page, '目标目录', '验收父目录 / 验收子目录')
  await page.getByRole('button', { name: '确认移动', exact: true }).click()
  await expect(
    row.getByRole('cell', { name: '验收父目录 / 验收子目录', exact: true }),
  ).toBeVisible()
  await expect(row.getByRole('cell', { name: '已发布', exact: true })).toBeVisible()
  await page.goto(parentUrl)
  await expect(page.getByRole('button', { name: '订单明细宽表', exact: true })).toBeVisible()
  await sidebar.getByRole('button', { name: '全部数据集', exact: true }).click()
  await page.goBack()
  await expect(page).toHaveURL(parentUrl)
  await page.reload()
  await expect(page.getByRole('button', { name: '订单明细宽表', exact: true })).toBeVisible()
  await page.goto(childUrl)
  await sidebar.getByRole('button', { name: '删除目录', exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: '删除', exact: true }).click()
  await expect(
    page.getByText('请先移动数据集和子目录，再删除空目录。', { exact: true }),
  ).toBeVisible()
  await page.getByRole('button', { name: '取消', exact: true }).click()
  await sidebar.getByRole('button', { name: '编辑目录', exact: true }).click()
  await page.getByRole('textbox', { name: '目录名称', exact: true }).fill('验收改名')
  page.once('dialog', (dialog) => dialog.dismiss())
  await page.getByRole('button', { name: '取消', exact: true }).click()
  await expect(page.getByRole('textbox', { name: '目录名称', exact: true })).toHaveValue('验收改名')
  await page.getByRole('button', { name: '保存', exact: true }).click()
  await expect(sidebar.getByText('验收改名', { exact: true })).toBeVisible()
  await page
    .getByRole('row')
    .filter({ hasText: '订单明细宽表' })
    .getByRole('button', { name: '移动到目录', exact: true })
    .click()
  await select(page, '目标目录', '交易分析')
  await page.getByRole('button', { name: '确认移动', exact: true }).click()
  await expect(page.getByRole('button', { name: '订单明细宽表', exact: true })).toHaveCount(0)
  await sidebar.getByRole('button', { name: '删除目录', exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: '删除', exact: true }).click()
  await expect(page).toHaveURL(/\/datasets$/)
  await page.reload()
  await expect(sidebar.getByText('验收改名', { exact: true })).toHaveCount(0)
  expect(errors).toEqual([])
})
test('subject domain filtering survives back navigation and reload; viewer controls are disabled', async ({
  page,
}) => {
  await page.goto('/warehouse/tables')
  await select(page, '主题域', '交易')
  await expect(page.getByRole('row').filter({ hasText: 'dwd_retail_1' })).toBeVisible()
  await expect(page.getByRole('row').filter({ hasText: 'dws_retail_2' })).toHaveCount(0)
  const filteredUrl = page.url()
  await select(page, '主题域', '客户')
  await expect(page.getByRole('row').filter({ hasText: 'dws_retail_2' })).toBeVisible()
  await page.goBack()
  await expect(page).toHaveURL(filteredUrl)
  await page.reload()
  await expect(page.getByRole('row').filter({ hasText: 'dwd_retail_1' })).toBeVisible()
  await page.evaluate(() => localStorage.setItem('jiuzhang.preference.role', 'viewer'))
  await page.goto('/datasets')
  await expect(page.getByRole('button', { name: '新建目录', exact: true })).toBeDisabled()
  await expect(page.getByRole('button', { name: '移动到目录', exact: true }).first()).toBeDisabled()
})
