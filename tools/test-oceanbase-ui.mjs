import { createRequire } from 'node:module'
import { readFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
const require=createRequire(new URL('../apps/web/package.json',import.meta.url))
const {chromium,expect}=require('@playwright/test')
const env={...process.env,...Object.fromEntries(readFileSync(new URL('../.env',import.meta.url),'utf8').split(/\r?\n/).filter(line=>line.includes('=')&&!line.startsWith('#')).map(line=>{const i=line.indexOf('=');return [line.slice(0,i),line.slice(i+1)]}))}
if(!env.OCEANBASE_USER||!env.OCEANBASE_PASSWORD){console.log('未验证：未配置 OceanBase 浏览器验收环境。');process.exit(0)}
const browser=await chromium.launch()
const page=await browser.newPage({viewport:{width:1280,height:1000}})
const errors=[]
page.on('pageerror',error=>errors.push(error.message))
async function capture(theme) {
  await expect(page.locator('.n-message')).toHaveCount(0,{timeout:15000})
  await expect(page.getByRole('button',{name:'测试连接',exact:true})).toBeEnabled()
  await page.evaluate(()=>Promise.all(document.getAnimations().filter(a=>a.effect?.getTiming().iterations!==Infinity).map(a=>a.finished.catch(()=>{}))))
  await page.screenshot({path:fileURLToPath(new URL('../.local/oceanbase-source-'+theme+'-1280.png',import.meta.url)),animations:'disabled'})
}
try {
  await page.goto('http://localhost:5175/login')
  await page.getByLabel('账号',{exact:true}).fill(env.JIUZHANG_BOOTSTRAP_USER)
  await page.getByLabel('密码',{exact:true}).fill(env.JIUZHANG_BOOTSTRAP_PASSWORD)
  await page.getByRole('button',{name:'登录',exact:true}).click()
  await page.waitForURL('**/overview')
  await page.goto('http://localhost:5175/sources/new')
  await page.getByRole('button',{name:'类型',exact:true}).click()
  await page.locator('.n-base-select-option__content').getByText('OceanBase (MySQL)',{exact:true}).click()
  await expect(page.getByLabel('端口',{exact:true})).toHaveValue('2881')
  await expect(page.getByRole('switch',{name:'启用 TLS',exact:true})).toBeChecked()
  await expect(page.getByText(/仅支持 MySQL 模式/)).toBeVisible()
  await page.getByLabel('名称',{exact:true}).fill('browser_ob_'+Date.now())
  await page.getByLabel('数据库主机',{exact:true}).fill(env.OCEANBASE_HOST)
  await page.getByLabel('端口',{exact:true}).fill(env.OCEANBASE_PORT)
  await page.getByLabel('数据库',{exact:true}).fill(env.OCEANBASE_DATABASE)
  await page.getByLabel('数据库账号',{exact:true}).fill(env.OCEANBASE_USER)
  await page.getByLabel('数据库密码',{exact:true}).fill('incorrect-acceptance-password')
  if(env.OCEANBASE_TLS==='false')await page.getByRole('switch',{name:'启用 TLS',exact:true}).uncheck()
  await page.getByRole('button',{name:'测试连接',exact:true}).click()
  await page.locator('.n-message').filter({hasText:'数据库连接失败'}).waitFor()
  await expect(page.getByLabel('数据库账号',{exact:true})).toHaveValue(env.OCEANBASE_USER)
  await page.getByLabel('数据库密码',{exact:true}).fill(env.OCEANBASE_PASSWORD)
  await page.getByRole('button',{name:'测试连接',exact:true}).click()
  await page.getByText('数据库连接成功',{exact:true}).waitFor()
  await capture('light')
  await page.getByRole('button',{name:'切换明暗主题',exact:true}).click()
  await capture('dark')
  await page.getByRole('button',{name:'保存',exact:true}).click()
  await page.waitForURL(/\/sources\/\d+$/)
  const id=page.url().split('/').at(-1)
  const saved=await (await page.request.get('http://localhost:5175/api/v1/sources/'+id)).json()
  expect(saved.data.type).toBe('OceanBase');expect(saved.data.credentialConfigured).toBe(true)
  expect(saved.data.connectionUsername).toBe(env.OCEANBASE_USER)
  await page.getByRole('button',{name:'编辑',exact:true}).click()
  await expect(page.getByLabel('数据库密码',{exact:true})).toHaveValue('')
  await expect(page.getByLabel('数据库账号',{exact:true})).toHaveValue(env.OCEANBASE_USER)
  await page.getByRole('button',{name:'测试连接',exact:true}).click()
  await page.getByText('数据库连接成功',{exact:true}).waitFor()
  await page.getByLabel('数据库',{exact:true}).fill('unsaved_change')
  await page.getByRole('button',{name:'取消',exact:true}).click()
  expect((await (await page.request.get('http://localhost:5175/api/v1/sources/'+id)).json()).data.settings.database).toBe(env.OCEANBASE_DATABASE)
  if(errors.length)throw new Error(JSON.stringify(errors))
  console.log('PASS OceanBase UI 1280x1000: type/defaults, full account, failure/retry/save, credential retention/cancel, light/dark')
} finally {await browser.close()}
