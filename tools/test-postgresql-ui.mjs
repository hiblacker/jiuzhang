import { createRequire } from 'node:module'
import { readFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
const require=createRequire(new URL('../apps/web/package.json',import.meta.url))
const {chromium,expect}=require('@playwright/test')
const env={...process.env,...Object.fromEntries(readFileSync(new URL('../.env',import.meta.url),'utf8').split(/\r?\n/).filter(line=>line.includes('=')&&!line.startsWith('#')).map(line=>{const i=line.indexOf('=');return [line.slice(0,i),line.slice(i+1)]}))}
if(!env.POSTGRESQL_SOURCE_PASSWORD)throw new Error('PostgreSQL source fixture not initialized')
const browser=await chromium.launch()
const page=await browser.newPage({viewport:{width:1280,height:1000}})
const errors=[]
page.on('pageerror',error=>errors.push(error.message))
async function capture(theme) {
  await expect(page.locator('.n-message')).toHaveCount(0,{timeout:15000})
  await expect(page.getByRole('button',{name:'测试连接',exact:true})).toBeEnabled()
  await page.evaluate(()=>Promise.all(document.getAnimations().filter(a=>a.effect?.getTiming().iterations!==Infinity).map(a=>a.finished.catch(()=>{}))))
  await page.screenshot({path:fileURLToPath(new URL('../.local/postgresql-source-'+theme+'-1280.png',import.meta.url)),animations:'disabled'})
}
try {
  await page.goto('http://localhost:5175/login')
  await page.getByLabel('账号',{exact:true}).fill(env.JIUZHANG_BOOTSTRAP_USER)
  await page.getByLabel('密码',{exact:true}).fill(env.JIUZHANG_BOOTSTRAP_PASSWORD)
  await page.getByRole('button',{name:'登录',exact:true}).click()
  await page.waitForURL('**/overview')
  await page.goto('http://localhost:5175/sources/new')
  await page.getByRole('button',{name:'类型',exact:true}).click()
  await page.locator('.n-base-select-option__content').getByText('PostgreSQL',{exact:true}).click()
  await expect(page.getByLabel('端口',{exact:true})).toHaveValue('5432')
  await expect(page.getByRole('switch',{name:'启用 TLS',exact:true})).toBeChecked()
  await expect(page.getByLabel('Schema',{exact:true})).toHaveValue('public')
  await expect(page.getByText(/默认端口 5432/)).toBeVisible()
  await page.getByLabel('名称',{exact:true}).fill('browser_pg_'+Date.now())
  await page.getByLabel('数据库主机',{exact:true}).fill('localhost')
  await page.getByLabel('端口',{exact:true}).fill('15433')
  await page.getByLabel('数据库',{exact:true}).fill('demo_retail')
  await page.getByLabel('数据库账号',{exact:true}).fill('jiuzhang_reader')
  await page.getByLabel('数据库密码',{exact:true}).fill('incorrect-acceptance-password')
  await page.getByLabel('Schema',{exact:true}).fill('Retail')
  await page.getByRole('button',{name:'测试连接',exact:true}).click()
  await page.locator('.n-message').filter({hasText:'数据库连接失败'}).waitFor()
  await expect(page.getByLabel('数据库账号',{exact:true})).toHaveValue('jiuzhang_reader')
  await page.getByLabel('数据库密码',{exact:true}).fill(env.POSTGRESQL_SOURCE_PASSWORD)
  await page.getByRole('button',{name:'测试连接',exact:true}).click()
  await page.getByText('数据库连接成功',{exact:true}).waitFor()
  await capture('light')
  await page.getByRole('button',{name:'切换明暗主题',exact:true}).click()
  await capture('dark')
  await page.getByRole('button',{name:'保存',exact:true}).click()
  await page.waitForURL(/\/sources\/\d+$/)
  const id=page.url().split('/').at(-1)
  const saved=await (await page.request.get('http://localhost:5175/api/v1/sources/'+id)).json()
  expect(saved.data.type).toBe('PostgreSQL');expect(saved.data.credentialConfigured).toBe(true)
  expect(saved.data.settings.schema).toBe('Retail')
  expect(saved.data.connectionUsername).toBe('jiuzhang_reader')
  await page.getByRole('button',{name:'编辑',exact:true}).click()
  await expect(page.getByLabel('数据库密码',{exact:true})).toHaveValue('')
  await expect(page.getByLabel('数据库账号',{exact:true})).toHaveValue('jiuzhang_reader')
  await page.getByRole('button',{name:'测试连接',exact:true}).click()
  await page.getByText('数据库连接成功',{exact:true}).waitFor()
  await page.getByLabel('Schema',{exact:true}).fill('unsaved_change')
  await page.getByRole('button',{name:'取消',exact:true}).click()
  expect((await (await page.request.get('http://localhost:5175/api/v1/sources/'+id)).json()).data.settings.schema).toBe('Retail')
  await page.goto('http://localhost:5175/datasets/new?sourceId='+id)
  await page.getByRole('button',{name:'定义方式',exact:true}).click()
  await page.getByText('自定义 SQL',{exact:true}).click()
  const catalog=page.getByRole('complementary',{name:'对象目录',exact:true})
  await catalog.getByRole('button',{name:'Orders',exact:true}).click()
  const editor=page.getByLabel('数据集 SQL 编辑器',{exact:true})
  await editor.fill('')
  await page.getByRole('button',{name:'插入表名（空 SQL 时生成 SELECT）',exact:true}).click()
  await expect(editor).toHaveText('SELECT * FROM "Orders"')
  const response=page.waitForResponse(r=>r.url().endsWith('/api/v1/datasets/preview')&&r.request().method()==='POST')
  await page.getByRole('button',{name:'运行 SQL',exact:true}).click()
  const preview=await response
  if(!preview.ok())throw new Error('PostgreSQL SQL preview failed: '+preview.status())
  const result=await preview.json()
  expect(result.data.rows).toHaveLength(100)
  expect(result.data.fields.find(field=>field.name==='amount').type).toBe('decimal(20,4)')
  expect(result.data.fields.find(field=>field.name==='active').type).toBe('boolean')
  await editor.fill('SELECT * FROM "Retail".')
  await editor.press('Control+Space')
  await page.locator('.cm-tooltip-autocomplete li').filter({hasText:/^Orders/}).first().click()
  await expect(editor).toHaveText('SELECT * FROM "Retail"."Orders"')
  if(errors.length)throw new Error(JSON.stringify(errors))
  console.log('PASS PostgreSQL UI 1280x1000: type/5432/public/TLS defaults, schema, failure/retry/save, credential retention/cancel, light/dark, native quoted SQL insertion/preview')
} finally {await browser.close()}
