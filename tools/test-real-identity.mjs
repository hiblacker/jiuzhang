import { createRequire } from 'node:module'
import { readFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
const require = createRequire(new URL('../apps/web/package.json', import.meta.url))
const { chromium } = require('@playwright/test')
const env = Object.fromEntries(readFileSync(fileURLToPath(new URL('../.env', import.meta.url)), 'utf8')
  .split(/\r?\n/).filter(Boolean).map(line => { const i = line.indexOf('='); return [line.slice(0,i), line.slice(i+1)] }))
const browser = await chromium.launch()
const page = await browser.newPage({ viewport: { width: 1280, height: 1000 } })
const errors = []
page.on('pageerror', e => errors.push(e.message))
try {
  await page.goto('http://localhost:5175/system/users')
  await page.getByLabel('账号', { exact: true }).fill(env.JIUZHANG_BOOTSTRAP_USER)
  await page.getByLabel('密码', { exact: true }).fill('wrong')
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await page.getByText('账号或密码不正确', { exact: true }).waitFor()
  await page.getByLabel('密码', { exact: true }).fill(env.JIUZHANG_BOOTSTRAP_PASSWORD)
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await page.waitForURL('**/system/users')
  await page.getByRole('table').waitFor()
  await page.reload()
  await page.getByRole('table').waitFor()
  if (await page.getByText('演示数据', { exact: true }).count()) throw new Error('Unexpected demo badge')
  await page.getByRole('button', { name: '新建用户', exact: true }).click()
  await page.getByLabel('账号', { exact: true }).fill('browser_' + Date.now())
  await page.getByLabel('密码', { exact: true }).fill(crypto.randomUUID())
  page.once('dialog', dialog => dialog.accept())
  await page.getByRole('button', { name: '取消', exact: true }).click()
  await page.keyboard.press('Escape')
  await page.getByRole('button', { name: '退出登录', exact: true }).hover()
  await page.getByText('修改密码', { exact: true }).click()
  await page.getByLabel('当前密码', { exact: true }).fill('wrong')
  await page.getByLabel('新密码（至少 12 个字符）', { exact: true }).fill(crypto.randomUUID())
  await page.getByRole('button', { name: '保存', exact: true }).click()
  await page.getByText('账号或密码不正确', { exact: true }).waitFor()
  await page.keyboard.press('Escape')
  await page.screenshot({ path: '/tmp/jiuzhang-real-users-1280.png' })
  await page.getByRole('button', { name: '退出登录', exact: true }).hover()
  await page.getByText('退出登录', { exact: true }).click()
  await page.waitForURL('**/login')
  if ((await page.request.get('http://localhost:5175/api/v1/session')).status() !== 401) throw new Error('Logout did not revoke session')
  if (errors.length) throw new Error(JSON.stringify(errors))
  console.log('PASS 1280x1000 real identity: bad login, users, refresh, form cancel, password failure, logout')
} finally { await browser.close() }
