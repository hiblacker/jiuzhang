import { createRequire } from 'node:module'
import { readFileSync } from 'node:fs'
const require = createRequire(new URL('../apps/web/package.json', import.meta.url))
const { chromium } = require('@playwright/test')
const env = Object.fromEntries(readFileSync(new URL('../.env', import.meta.url), 'utf8').split(/\r?\n/).filter(Boolean).map(line => { const n = line.indexOf('='); return [line.slice(0,n), line.slice(n+1)] }))
const browser = await chromium.launch()
const page = await browser.newPage({ viewport: { width: 1280, height: 1000 } })
const errors = []
page.on('pageerror', error => errors.push(error.message))
try {
  await page.goto('http://localhost:5175/login')
  await page.getByLabel('账号', { exact: true }).fill(env.JIUZHANG_BOOTSTRAP_USER)
  await page.getByLabel('密码', { exact: true }).fill(env.JIUZHANG_BOOTSTRAP_PASSWORD)
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await page.waitForURL('**/overview')
  await page.goto('http://localhost:5175/sources/new')
  await page.getByLabel('名称', { exact: true }).fill('browser_mysql_' + Date.now())
  await page.getByLabel('数据库主机', { exact: true }).fill('127.0.0.1')
  await page.getByLabel('端口', { exact: true }).fill('13306')
  await page.getByLabel('数据库', { exact: true }).fill('demo_retail')
  await page.getByLabel('数据库账号', { exact: true }).fill('root')
  await page.getByLabel('数据库密码', { exact: true }).fill('incorrect-password')
  await page.getByRole('switch', { name: '启用 TLS', exact: true }).uncheck()
  await page.getByRole('button', { name: '测试连接', exact: true }).click()
  await page.locator('.n-message').filter({ hasText: '数据库连接失败' }).waitFor()
  if (await page.getByText('操作未完成，请重试', { exact: true }).isVisible()) throw new Error('Unmapped source error')
  if (await page.getByLabel('数据库账号', { exact: true }).inputValue() !== 'root') throw new Error('Failed test discarded draft')
  await page.getByLabel('数据库密码', { exact: true }).fill(env.SOURCE_ROOT_PASSWORD)
  await page.getByRole('button', { name: '测试连接', exact: true }).click()
  await page.getByText('数据库连接成功', { exact: true }).waitFor()
  await page.getByRole('button', { name: '保存', exact: true }).click()
  await page.waitForURL(/\/sources\/\d+$/)
  const sourceId=page.url().split('/').at(-1)
  const response=await page.request.get('http://localhost:5175/api/v1/sources/'+sourceId+'/objects')
  const object=(await response.json()).data.find(x=>x.name==='orders')
  const fieldResponse=await page.request.get('http://localhost:5175/api/v1/sources/'+sourceId+'/objects/'+object.id+'/fields')
  const fieldData=(await fieldResponse.json()).data
  const idField=fieldData.find(x=>x.name==='id')
  if (idField?.description !== '订单主键') throw new Error('Column comment was not returned: '+JSON.stringify(idField))
  await page.goto('http://localhost:5175/sources/'+sourceId+'?objectId='+object.id)
  await page.getByRole('heading', { name: 'orders', exact: true }).waitFor()
  const directory=page.getByRole('complementary', { name: '对象目录', exact: true })
  const search=directory.getByRole('textbox', { name: '搜索表名', exact: true })
  await search.fill('orders')
  await directory.getByText('orders', { exact: true }).waitFor()
  if (await directory.locator('[data-object-node^="object:"]:visible').count() !== 1) throw new Error('Table search did not filter the directory')
  await search.fill('')
  await page.getByRole('cell', { name: 'id', exact: true }).waitFor()
  await page.getByRole('cell', { name: 'amount', exact: true }).waitFor()
  await page.getByRole('cell', { name: '订单主键', exact: true }).waitFor()
  if (await page.getByText('9007199254740993', { exact: true }).count()) throw new Error('Source rows are visible in the directory')
  await page.screenshot({ path: '/tmp/jiuzhang-source-directory-1280.png' })
  await page.getByRole('button', { name: '编辑', exact: true }).click()
  await page.getByLabel('数据库密码', { exact: true }).waitFor()
  if (await page.getByLabel('数据库密码', { exact: true }).inputValue()) throw new Error('Credential returned to browser')
  await page.getByRole('button', { name: '测试连接', exact: true }).click()
  await page.getByText('数据库连接成功', { exact: true }).waitFor()
  await page.screenshot({ path: '/tmp/jiuzhang-real-source-1280.png' })
  if (errors.length) throw new Error(JSON.stringify(errors))
  console.log('PASS real MySQL browser at 1280x1000: wrong-password message/draft retention/privileged-account create/test/table search/field descriptions/edit credential retention')
} finally { await browser.close() }
