async function responseSchema(response, template, method='post') {
  expect(response.ok()).toBeTruthy()
  const body=await response.json()
  const schema=contract.paths[template][method].responses[String(response.status())].content['application/json'].schema
  const validate=ajv.compile({ ...schema, components: contract.components })
  if(!validate(body)) throw new Error(JSON.stringify(validate.errors))
  return body.data
}
